# data-raw/emoji_emotion_lexicon.R
# -----------------------------------------------------------------------------
# Builds the bundled `emoji_emotion_lexicon` dataset from EmoTag1200
# (Shoeb & de Melo 2020, EMNLP).
#
#   Abu Awal Md Shoeb, Gerard de Melo (2020). EmoTag1200: Understanding the
#   Association between Emojis and Emotions. EMNLP 2020.
#   https://aclanthology.org/2020.emnlp-main.720/
#
# Data:    https://github.com/abushoeb/EmoTag  (data/EmoTag1200-scores.csv)
# License: MIT
#
# EmoTag1200 contains human-annotated emotion-association scores in [0, 1] for
# the 8 Plutchik emotions (anger, anticipation, disgust, fear, joy, sadness,
# surprise, trust) for the 150 most popular Twitter emoji. We keep the glyph and
# all eight scores, drop the redundant hex code, and normalise the glyph through
# the same codepoint key (stripping U+FE0F) used everywhere else in the package.
# That is what lets qualified text join to an unqualified lexicon entry: the
# lexicon stores the bare U+2764 heart, and without the key a user's
# U+2764 U+FE0F would miss it. (This used to cite next_release.md §4.1, which
# is a planning document rewritten each release -- §4.1 is now about skin-tone
# modifiers, so the pointer had gone stale. The reason is stated here instead.)
#
#   source("data-raw/emoji_emotion_lexicon.R")
# -----------------------------------------------------------------------------

library(dplyr)

# EmoTag1200's scores, from the one commit of the EmoTag repository that has
# ever touched them, committed xz-compressed under data-raw/lexicons/ so the
# dataset rebuilds offline and byte for byte (9,624 bytes, md5
# aceacaf5525133a3c9d350e713c88326). TIDYEMOJI_FETCH=true downloads it again;
# TIDYEMOJI_LEXICONS names another directory to read it from.
url <- paste0("https://raw.githubusercontent.com/abushoeb/EmoTag/",
              "0951f7f8c5e9c8afed5e78689548d5586d1a8c07/data/",
              "EmoTag1200-scores.csv")
src <- file.path(Sys.getenv("TIDYEMOJI_LEXICONS",
                            file.path("data-raw", "lexicons")),
                 "EmoTag1200-scores.csv.xz")
if (identical(tolower(Sys.getenv("TIDYEMOJI_FETCH")), "true")) {
  tmp <- tempfile(fileext = ".csv")
  utils::download.file(url, tmp, mode = "wb", quiet = TRUE)
  con <- xzfile(src, open = "wb", compression = 9)
  writeBin(readBin(tmp, "raw", file.info(tmp)$size), con)
  close(con)
}

# Read as bytes and marked UTF-8, so the session's locale cannot touch the
# glyphs; empty fields and "NA" are missing, as readr::read_csv() had them.
emotions <- c("anger", "anticipation", "disgust", "fear",
              "joy", "sadness", "surprise", "trust")
raw <- utils::read.csv(xzfile(src), encoding = "UTF-8", check.names = FALSE,
                       na.strings = c("", "NA"), stringsAsFactors = FALSE,
                       colClasses = stats::setNames(rep("character", 8L),
                                                    emotions))

# R's own decimal parser, behind read.csv() and as.numeric(), is not
# correctly rounded: it misreads one of the sentiment lexicon's 969 positions
# by one unit in the last place, and can miss more where long double is a
# double. Every score is a plain decimal of at most nine places, so it is read
# exactly instead, as an integer over a power of ten: both are exact doubles,
# and IEEE division rounds correctly.
exact_decimal <- function(s) {
  stopifnot(all(grepl("^[0-9]+([.][0-9]{1,9})?$", s)))
  vapply(strsplit(s, ".", fixed = TRUE), function(p) {
    k <- if (length(p) > 1L) nchar(p[[2L]]) else 0L
    (as.numeric(p[[1L]]) * 10^k + if (k) as.numeric(p[[2L]]) else 0) / 10^k
  }, numeric(1))
}
raw[emotions] <- lapply(raw[emotions], exact_decimal)

# Codepoint key (strip U+FE0F) so qualified glyphs in user text resolve to the
# (unqualified) emoji stored in the lexicon.
# The package's own key function, not a copy of it. Two verbatim copies used
# to live in data-raw/, and both had drifted: neither had the guard that makes
# a selector-only string key to NA rather than "" (one sentinel, not two), and
# neither coerced or rejected undecodable input. The bundled `key` columns
# were therefore generated by a function that no longer matched the one used
# to look them up.
emoji_key2 <- function(glyphs) tidyEmoji:::emoji_key(glyphs)

emoji_emotion_lexicon <- raw %>%
  transmute(
    emoji = emoji,
    name  = name,
    anger        = as.numeric(anger),
    anticipation = as.numeric(anticipation),
    disgust      = as.numeric(disgust),
    fear         = as.numeric(fear),
    joy          = as.numeric(joy),
    sadness      = as.numeric(sadness),
    surprise     = as.numeric(surprise),
    trust        = as.numeric(trust)
  ) %>%
  filter(!is.na(emoji), emoji != "") %>%
  mutate(key = emoji_key2(emoji)) %>%
  # If two stored glyphs collapse to the same key, keep the first.
  group_by(key) %>%
  slice(1L) %>%
  ungroup() %>%
  select(key, emoji, name, all_of(emotions)) %>%
  as.data.frame(stringsAsFactors = FALSE)

message("emoji_emotion_lexicon: ", nrow(emoji_emotion_lexicon), " emoji across ",
        length(emotions), " emotions")
stopifnot(all(emotions %in% names(emoji_emotion_lexicon)))
stopifnot(!anyDuplicated(emoji_emotion_lexicon$key))

# Attribute order is part of the .rda but not of the value, and dplyr and
# tibble releases differ in it; fix it at names, row.names, class, the order
# the bundled file has always had (data-raw/emoji_sentiment_lexicon.R says
# why).
emoji_emotion_lexicon <- structure(
  unclass(emoji_emotion_lexicon)[names(emoji_emotion_lexicon)],
  row.names = c(NA, -nrow(emoji_emotion_lexicon)), class = "data.frame")

if (!identical(tolower(Sys.getenv("TIDYEMOJI_WRITE")), "false")) {
  save(emoji_emotion_lexicon,
       file = file.path("data", "emoji_emotion_lexicon.rda"), compress = "xz")
}
